package io.github.j3ffx.nuance.core.charts

import io.github.j3ffx.nuance.core.Rgb
import io.github.j3ffx.nuance.core.color.Oklab
import io.github.j3ffx.nuance.core.color.Srgb
import io.github.j3ffx.nuance.core.color.Vec3
import io.github.j3ffx.nuance.core.correction.CorrectionMetrics
import io.github.j3ffx.nuance.core.cvd.Axis
import io.github.j3ffx.nuance.core.cvd.CvdProfile
import kotlin.math.PI
import kotlin.math.cos
import kotlin.math.sin

/** An sRGB image as packed 0xAARRGGBB pixels, row by row. */
class SyntheticImage(val width: Int, val height: Int, val pixels: IntArray) {
    operator fun get(x: Int, y: Int) = pixels[y * width + x]

    /** The same image with [f] applied to every pixel (through a cache: charts have few colours). */
    fun map(f: (Rgb) -> Rgb): SyntheticImage {
        val cache = HashMap<Int, Int>()
        return SyntheticImage(
            width,
            height,
            IntArray(pixels.size) { i ->
                cache.getOrPut(pixels[i]) { pack(f(unpack(pixels[i]))) }
            }
        )
    }

    companion object {
        fun pack(c: Rgb): Int {
            fun ch(v: Float) = (v.coerceIn(0f, 1f) * 255f + 0.5f).toInt()
            return (0xFF shl 24) or (ch(c.r) shl 16) or (ch(c.g) shl 8) or ch(c.b)
        }

        fun unpack(p: Int) = Rgb(((p shr 16) and 0xFF) / 255f, ((p shr 8) and 0xFF) / 255f, (p and 0xFF) / 255f)
    }
}

/**
 * Test images generated by code: nothing photographed. They feed the golden tests, the
 * measurement report and the dev variant's fake camera source.
 */
object SyntheticCharts {
    /** 216 colours of a 6×6×6 cube, 16 greys, 36 hues at two lightnesses, and skin tones. */
    fun patches(): List<Rgb> = buildList {
        val steps = listOf(0f, 0.2f, 0.4f, 0.6f, 0.8f, 1f)
        for (r in steps) for (g in steps) for (b in steps) add(Rgb(r, g, b))
        for (i in 0..15) add(Rgb(i / 15f, i / 15f, i / 15f))
        for (l in listOf(0.55, 0.8)) for (h in 0 until 360 step 10) add(oklch(l, 0.1, h.toDouble()))
        for (c in CorrectionMetrics.skinTones()) add(Srgb.fromLinear(c).clamped())
    }

    /** A grid of square [patches], [cell] pixels each. */
    fun patchGrid(columns: Int = 24, cell: Int = 16): SyntheticImage {
        val list = patches()
        val rows = (list.size + columns - 1) / columns
        val w = columns * cell
        val h = rows * cell
        return SyntheticImage(
            w,
            h,
            IntArray(w * h) { i ->
                val index = (i / w / cell) * columns + (i % w) / cell
                SyntheticImage.pack(list.getOrElse(index) { Rgb.Black })
            }
        )
    }

    /** Hues across, lightness down (Oklch, constant chroma), with a grey ramp on the bottom rows. */
    fun hueSweep(width: Int = 360, height: Int = 120): SyntheticImage {
        val grayRows = height / 6
        return SyntheticImage(
            width,
            height,
            IntArray(width * height) { i ->
                val x = i % width
                val y = i / width
                val c = if (y >= height - grayRows) {
                    val g = x / (width - 1f)
                    Rgb(g, g, g)
                } else {
                    oklch(0.85 - 0.45 * y / (height - grayRows), 0.11, 360.0 * x / width)
                }
                SyntheticImage.pack(c)
            }
        )
    }

    /**
     * Stripes of colour pairs a profile confuses: each band alternates its two colours. Typical
     * vision sees every stripe; the simulated profile sees flat bands, until corrected.
     */
    fun confusionStripes(
        axis: Axis,
        width: Int = 360,
        height: Int = 120,
        bands: Int = 6,
        stripe: Int = 12
    ): SyntheticImage {
        val pairs = CorrectionMetrics.confusionPairs(CvdProfile(axis, 1.0))
        val picked = (0 until bands).map { pairs[(it * pairs.size) / bands] }
        val bandHeight = height / bands
        return SyntheticImage(
            width,
            height,
            IntArray(width * height) { i ->
                val x = i % width
                val y = i / width
                val (a, b) = picked[(y / bandHeight).coerceAtMost(bands - 1)]
                SyntheticImage.pack(Srgb.fromLinear(if ((x / stripe) % 2 == 0) a else b).clamped())
            }
        )
    }

    private fun oklch(l: Double, c: Double, h: Double): Rgb {
        val rad = h * PI / 180
        val linear = Oklab.toLinear(Vec3(l, c * cos(rad), c * sin(rad)))
        return Srgb.fromLinear(CorrectionMetrics.clampLinear(linear)).clamped()
    }
}
